import { test } from "node:test";
import assert from "node:assert/strict";
import { sign } from "node:crypto";
import { deviceMessage, verifyDeviceSignature, sha256Hex } from "../src/crypto.ts";
import { device } from "./helpers.ts";

test("device signature covers body hash", () => {
  const d = device();
  const body = '{"device_id":"abc"}';
  const ts = Math.floor(Date.now() / 1000);
  const hash = sha256Hex(body);
  const message = deviceMessage("refresh", d.id, ts, hash);
  const sig = sign("sha256", Buffer.from(message), d.privateKey).toString("base64");
  assert.equal(verifyDeviceSignature(d.key, "refresh", d.id, ts, sig, hash), true);
  assert.equal(verifyDeviceSignature(d.key, "refresh", d.id, ts, sig, sha256Hex("{}")), false);
});

// Generated by Swift CryptoKit P256.Signing using X9.63 public key and DER signature.
test("verifies Swift CryptoKit signature vector", () => {
  const key = "BIzt0dou5bcpxSILELf7URP222t0fSTgF0yY34FcP2M7ZlXdirnKW9KqEP3WFb+6HSgNIW53/vctLnCL2QOiU9o=";
  const sig = "MEYCIQCE9b2UY3uw8m2TtHcugtuPWtlq9SAtN1Sv4fUNf2beaAIhAINQrDGY3ZdE3omXl/zeRgAomWOkbbH3s473Zme41c/e";
  assert.equal(verifyDeviceSignature(key, "poll", "a".repeat(64), 1700000000, sig, sha256Hex("")), true);
});
